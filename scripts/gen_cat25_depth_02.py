    assert EXPECTED_NEW_UC_COUNT == 112
    for section in SECTIONS:
        sub = section["sub"]
        expected = TARGET_COUNT_BY_SUB[sub]
        actual = len(section["rows"])
        assert actual == expected, f"subcategory {sub} expected {expected} rows, found {actual}"

    writer = Cat25Writer(append=True)
    for section in SECTIONS:
        emit(
            writer,
            section["sub"],
            section["app"],
            section["ds"],
            section["refs"],
            section["rows"],
        )

    added, counts = writer.summary()
    assert added == EXPECTED_NEW_UC_COUNT, f"expected {EXPECTED_NEW_UC_COUNT}, wrote {added}"
    print(f"Generated {added} cat-25 UCs across {len(counts)} subcategories.")
    return added, counts


