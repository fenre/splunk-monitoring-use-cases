def generate() -> None:
    counts, existing_titles = _load_existing_inventory()
    w = Cat25Writer(append=True)
    planned_titles: set[str] = set()

    for sub, config in CASES.items():
        for case in config["cases"]:
            title = case["title"]
            if title in planned_titles:
                raise RuntimeError(f"duplicate planned title in script: {title}")
            planned_titles.add(title)

    for sub in [str(i) for i in range(1, 16)]:
        config = CASES[sub]
        cases = config["cases"]
        needed = max(0, TARGET_PER_SUBCATEGORY - counts.get(sub, 0))
        emitted = 0
        for case in cases:
            if case["title"] in existing_titles:
                continue
            if emitted >= needed:
                break
            w.U(
                sub,
                case["title"],
                case["crit"],
                case["diff"],
                case["mtypes"],
                case["spl"],
                case["desc"],
                case["val"],
                case["impl"],
                case["viz"],
                case["grandma_body"],
                R(*case["refs"]),
                config["app"],
                config["ds"],
                pillar=case["pillar"] or config.get("pillar", "Platform"),
            )
            existing_titles.add(case["title"])
            emitted += 1
        if emitted < needed:
            raise RuntimeError(
                f"subcategory 25.{sub} needs {needed} new UCs but script only has {emitted} available"
            )

    print(w.summary())


if __name__ == "__main__":
    generate()
