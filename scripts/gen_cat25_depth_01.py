def _spl(*lines: str) -> str:
    return "\n".join(lines)


def _case(
    title: str,
    crit: str,
    diff: str,
    mtypes: list[str],
    spl: str,
    desc: str,
    val: str,
    impl: str,
    viz: str,
    grandma_body: str,
    refs: tuple[tuple[str, str], ...],
    pillar: str | None = None,
) -> dict[str, object]:
    return {
        "title": title,
        "crit": crit,
        "diff": diff,
        "mtypes": mtypes,
        "spl": spl,
        "desc": desc,
        "val": val,
        "impl": impl,
        "viz": viz,
        "grandma_body": grandma_body,
        "refs": refs,
        "pillar": pillar,
    }


def _load_existing_inventory() -> tuple[dict[str, int], set[str]]:
    counts = {str(i): 0 for i in range(1, 16)}
    titles: set[str] = set()
    for path in sorted(CAT25.glob("UC-25.*.*.json")):
        match = re.match(r"UC-25\.(\d+)\.(\d+)\.json$", path.name)
        if not match:
            continue
        sub = match.group(1)
        if sub not in counts:
            continue
        counts[sub] += 1
        data = json.loads(path.read_text(encoding="utf-8"))
        title = data.get("title")
        if isinstance(title, str) and title:
            titles.add(title)
    return counts, titles


