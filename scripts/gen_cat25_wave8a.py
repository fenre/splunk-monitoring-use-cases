def _spl(*lines: str) -> str:
    return "\n".join(lines)


def _case(
    title: str,
    crit: str,
    diff: str,
    mtypes: list[str],
    spl: str,
    desc: str,
    val: str,
    impl: str,
    viz: str,
    grandma_body: str,
) -> dict[str, object]:
    return {
        "title": title,
        "crit": crit,
        "diff": diff,
        "mtypes": mtypes,
        "spl": spl,
        "desc": desc,
        "val": val,
        "impl": impl,
        "viz": viz,
        "grandma_body": grandma_body,
    }


