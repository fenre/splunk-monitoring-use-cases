def _gcp_entry(title: str, desc: str, val: str, methods: tuple[str, ...]) -> TaxonomyEntry:
    m_clause = " OR ".join(f'protoPayload.methodName="*{m}*" OR protoPayload.methodName="{m}"' for m in methods)
    return TaxonomyEntry(
        subcategory="4.3",
        title=f"GCP {title}",
        service="gcp",
        index="gcp",
        sourcetype="google:gcp:audit",
        spl_filter=f"({m_clause})",
        criticality="high",
        difficulty="beginner",
        monitoring_type=("Security", "Audit"),
        splunk_pillar="Security",
        description=desc,
        value=val,
        implementation=(
            "Export Cloud Audit Logs to Pub/Sub; configure `Splunk_TA_google-cloudplatform` "
            "Pub/Sub input into `index=gcp`. Validate protoPayload.methodName extractions."
        ),
        visualization="Events list, methodName timeline, principalEmail table.",
        app="Splunk Add-on for Google Cloud Platform (`Splunk_TA_google-cloudplatform`, Splunkbase 3088)",
        equipment=("gcp",),
        equipment_models=("gcp_audit_log",),
        mitre_attack=("T1078.004",),
        cim_models=("Change",),
        wave="walk",
        prerequisite_uc="4.3.41",
        nist_control="AU-2",
        cis_control="2.1",
        splunkbase_id=3088,
        splunkbase_name="Splunk Add-on for Google Cloud Platform",
        vendor_ref_title="Cloud Audit Logs overview",
        vendor_ref_url="https://cloud.google.com/logging/docs/audit",
        table_fields="_time protoPayload.methodName protoPayload.authenticationInfo.principalEmail resource.labels.project_id",
    )


