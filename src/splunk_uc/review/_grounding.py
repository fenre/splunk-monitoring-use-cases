"""Grounding bundle for review prompts.

Collects the repository documents a reviewer needs to judge correctness
without guessing: the subcategory's integration guide (keyword-ranked
excerpt), the subcategory metadata from ``_category.json``, the cached
Splunkbase listings for every cited app ID, the matching domain pack, and
sibling-UC titles / data sources for cross-UC coherence.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

from splunk_uc.audits._template_fingerprints import SPLUNKBASE_TOKEN_RE, extract_domain_tokens
from splunk_uc.review._ledger import CONTENT_DIR, REPO_ROOT
from splunk_uc.tools.lift._domain_packs import format_pack_excerpt, infer_pack_id, load_domain_pack

SPLUNKBASE_CATALOG = REPO_ROOT / "data" / "splunkbase-catalog.json"
HEADING_RE = re.compile(r"^(#{2,4})\s+(.*)$", re.MULTILINE)


def subcategory_id(uc: dict[str, Any]) -> str:
    parts = str(uc.get("id", "")).removeprefix("UC-").split(".")
    return ".".join(parts[:2]) if len(parts) >= 2 else ""


@lru_cache(maxsize=64)
def load_category_meta(category_dir: str) -> dict[str, Any]:
    path = CONTENT_DIR / category_dir / "_category.json"
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return payload if isinstance(payload, dict) else {}


def subcategory_meta(category_dir: str, sub_id: str) -> dict[str, Any]:
    for sub in load_category_meta(category_dir).get("subcategories") or []:
        if isinstance(sub, dict) and str(sub.get("id")) == sub_id:
            return sub
    return {}


@lru_cache(maxsize=1)
def _splunkbase_apps() -> dict[str, Any]:
    try:
        payload = json.loads(SPLUNKBASE_CATALOG.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    apps = payload.get("apps") if isinstance(payload, dict) else None
    return apps if isinstance(apps, dict) else {}


def cited_splunkbase_ids(uc: dict[str, Any]) -> list[str]:
    ids: set[str] = set()
    for field in ("app", "dataSources", "implementation", "detailedImplementation"):
        value = uc.get(field)
        if isinstance(value, str):
            for match in SPLUNKBASE_TOKEN_RE.finditer(value):
                ids.add(match.group(1) or match.group(2))
    for ref in uc.get("references") or []:
        if isinstance(ref, dict) and isinstance(ref.get("url"), str):
            for match in SPLUNKBASE_TOKEN_RE.finditer(ref["url"]):
                ids.add(match.group(1) or match.group(2))
    return sorted(i for i in ids if i)


def splunkbase_listings(app_ids: list[str]) -> list[dict[str, Any]]:
    apps = _splunkbase_apps()
    out: list[dict[str, Any]] = []
    for app_id in app_ids:
        listing = apps.get(app_id)
        if listing is None:
            out.append({"id": app_id, "status": "not in cached data/splunkbase-catalog.json"})
            continue
        out.append(
            {
                "id": app_id,
                "displayName": listing.get("displayName"),
                "name": listing.get("name"),
                "category": listing.get("category"),
                "cloudVetted": listing.get("cloudVetted"),
                "url": listing.get("url"),
            }
        )
    return out


def split_sections(markdown: str) -> list[tuple[str, str]]:
    """Split a guide into ``(heading, body)`` sections at ##/###/#### headings."""
    matches = list(HEADING_RE.finditer(markdown))
    if not matches:
        return [("", markdown)]
    sections: list[tuple[str, str]] = []
    if matches[0].start() > 0:
        sections.append(("", markdown[: matches[0].start()]))
    for idx, match in enumerate(matches):
        end = matches[idx + 1].start() if idx + 1 < len(matches) else len(markdown)
        sections.append((match.group(2).strip(), markdown[match.start() : end]))
    return sections


def guide_excerpt(guide_rel: str, keywords: set[str], *, max_chars: int) -> str:
    """Highest-scoring guide sections for ``keywords``, in document order, within ``max_chars``."""
    if not guide_rel or max_chars <= 0:
        return ""
    path = REPO_ROOT / guide_rel
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return ""
    text = text.split("<!-- BEGIN-AUTOGENERATED-SOURCES -->", 1)[0]
    sections = split_sections(text)
    lowered_keywords = {k.lower() for k in keywords if len(k) >= 3}
    scored = []
    for idx, (heading, body) in enumerate(sections):
        lower = body.lower()
        score = sum(lower.count(k) for k in lowered_keywords)
        scored.append((score, idx, heading, body))
    chosen: list[tuple[int, str]] = []
    used = 0
    for score, idx, _heading, body in sorted(scored, key=lambda s: (-s[0], s[1])):
        if score == 0 and chosen:
            break
        if used + len(body) > max_chars:
            if not chosen:
                chosen.append((idx, body[:max_chars]))
            continue
        chosen.append((idx, body))
        used += len(body)
    return "\n".join(body.strip() for _, body in sorted(chosen)).strip()


def uc_keywords(uc: dict[str, Any]) -> set[str]:
    keywords = set(extract_domain_tokens(uc))
    keywords = {k for k in keywords if not k.startswith("splunkbase_")}
    for field in ("dataSources", "app"):
        value = uc.get(field)
        if isinstance(value, str):
            keywords.update(re.findall(r"`([^`]{3,60})`", value))
    return keywords


def sibling_summaries(
    category_dir: str,
    sub_id: str,
    *,
    exclude: set[str],
    limit: int = 40,
) -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    pattern = f"UC-{sub_id}.*.json"
    paths = sorted(
        (CONTENT_DIR / category_dir).glob(pattern),
        key=lambda p: [int(x) for x in p.stem.removeprefix("UC-").split(".") if x.isdigit()],
    )
    for path in paths:
        try:
            uc = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        uc_id = f"UC-{uc.get('id')}"
        if uc_id in exclude:
            continue
        out.append(
            {
                "id": uc_id,
                "title": str(uc.get("title", "")),
                "dataSources": str(uc.get("dataSources", ""))[:240],
            }
        )
        if len(out) >= limit:
            break
    return out


def build_grounding(
    entries: list[tuple[Path, dict[str, Any]]],
    *,
    max_guide_chars: int,
    sibling_limit: int,
) -> dict[str, Any]:
    """Grounding shared by every UC in ``entries`` (all from one subcategory for triage)."""
    path0, uc0 = entries[0]
    category_dir = path0.parent.name
    sub_id = subcategory_id(uc0)
    sub = subcategory_meta(category_dir, sub_id)
    keywords: set[str] = set()
    app_ids: set[str] = set()
    for _, uc in entries:
        keywords |= uc_keywords(uc)
        app_ids.update(cited_splunkbase_ids(uc))
    guide_rel = str(sub.get("guide") or "")
    pack_id = infer_pack_id(path0)
    pack = load_domain_pack(pack_id) if pack_id else None
    return {
        "category": category_dir,
        "subcategory": {k: v for k, v in sub.items() if k not in ("useCaseCount",)},
        "guide": guide_rel,
        "guide_excerpt": guide_excerpt(guide_rel, keywords, max_chars=max_guide_chars),
        "splunkbase": splunkbase_listings(sorted(app_ids)),
        "domain_pack": {"id": pack_id, "excerpt": format_pack_excerpt(pack)} if pack else None,
        "siblings": sibling_summaries(
            category_dir,
            sub_id,
            exclude={f"UC-{uc.get('id')}" for _, uc in entries},
            limit=sibling_limit,
        ),
    }
